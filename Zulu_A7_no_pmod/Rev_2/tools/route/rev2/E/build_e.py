"""build_e.py: strategy E inputs.
  E1 (the brief): prep/model.json + B's hand USB pair + CHAN10 re-route as fixed copper.
      model_E1.json, rip_E1.json (prep rip + the hand plan's CHAN10 removals)
  E2 (minimal rip): every prep-ripped item that is still legal on base_moved (exact route_check clearance against the
      moved pads, the surviving copper, the hand USB copper and everything restored so far) is put back; USB_D_P/N
      stay ripped (the hand pair replaces them). Dangling restored copper is left for compose_plan to trim.
      model_E2.json, rip_E2.json
usb_plan.json is the hand pair (generated by B/usb_hand.py into this folder)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import elib as E  # noqa: E402

base = E.load(os.path.join(E.PREP, 'base_moved.json'))
rip = E.load(os.path.join(E.PREP, 'rip.json'))
usb = E.load(os.path.join(E.EDIR, 'usb_plan.json'))
usb_v = [dict(v, span=E.span(v)) for v in usb['vias']]

# E1
rm_t = rip['remove'] + usb['remove']
rm_v = rip['remove_vias'] + usb['remove_vias']
M1 = E.apply(base, rm_t, rm_v, usb['tracks'], usb_v)
E.dump(M1, os.path.join(E.EDIR, 'model_E1.json'))
E.dump({'remove': rm_t, 'remove_vias': rm_v}, os.path.join(E.EDIR, 'rip_E1.json'), 0)
print('E1: %d tracks %d vias' % (len(M1['tracks']), len(M1['vias'])))

# E2: start from E1 and restore
NO = {'USB_D_P', 'USB_D_N'}
ck = E.Checker(M1)
restored_t, restored_v = [], []
cand_v = [v for v in rip['remove_vias'] if v['net'] not in NO]
cand_t = [t for t in rip['remove'] if t['net'] not in NO]
# vias first (columns together), then tracks; repeat until nothing more fits
changed = True
while changed:
    changed = False
    for v in list(cand_v):
        if not ck.via_bad(v):
            ck.add_via(v)
            restored_v.append(v)
            cand_v.remove(v)
            changed = True
    for t in list(cand_t):
        if not ck.track_bad(t):
            ck.add_track(t)
            restored_t.append(t)
            cand_t.remove(t)
            changed = True
rk, rvk = {E.tkey(t) for t in restored_t}, {E.vkey(v) for v in restored_v}
rm2_t = [t for t in rm_t if E.tkey(t) not in rk]
rm2_v = [v for v in rm_v if E.vkey(v) not in rvk]
M2 = E.apply(base, rm2_t, rm2_v, usb['tracks'], usb_v)
E.dump(M2, os.path.join(E.EDIR, 'model_E2.json'))
E.dump({'remove': rm2_t, 'remove_vias': rm2_v}, os.path.join(E.EDIR, 'rip_E2.json'), 0)
from collections import Counter
print('E2: restored %d tracks %d vias; still ripped %d tracks %d vias' % (len(restored_t), len(restored_v), len(rm2_t), len(rm2_v)))
print(' restored by net', dict(Counter(t['net'] for t in restored_t) + Counter(v['net'] for v in restored_v)))
print(' still ripped by net', dict(Counter(t['net'] for t in rm2_t) + Counter(v['net'] for v in rm2_v)))
for M, n in ((M1, 'E1'), (M2, 'E2')):
    oc = E.C.open_count(E.C.islands(M))
    print(n, 'open', sum(oc.values()), dict(sorted(oc.items(), key=lambda kv: -kv[1])))

# E2 as a seed on E1 (rippable router copper): restored items, vias as from/to objects
seed = {'tracks': [dict(t) for t in restored_t],
        'vias': [{'net': v['net'], 'x': v['x'], 'y': v['y'], 'size': v['size'], 'hole': v['hole'],
                  'from': E.span(v)[0], 'to': E.span(v)[-1]} for v in restored_v], 'remove': []}
E.dump(seed, os.path.join(E.EDIR, 'seed_E2.json'), 0)
print('seed_E2: %d tracks %d vias' % (len(seed['tracks']), len(seed['vias'])))

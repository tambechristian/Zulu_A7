"""3D component bodies for the Asar A7 board (2026-11-19, ported from Zulu_A7_no_pmod/Rev_2): one extruded box per body,
so Altium's Component Clearance rule checks real bodies instead of each part's bounding rectangle.

    python tools/release_body_gate.py          (refreshes tools/route/body_gate/model.json + comps.json from the board)
    python tools/emit_bodies.py                -> tools/AsarBodies3D.pas / .PrjScr  (+ tools/route/bodies3d/bodies.json)

The outline of each body is the one tools/body_check.py uses for the release gate (datasheet size centred on the pads,
the connector outlines in tools/body_mech.json -- X4 as its housing plus the two legs either side of the pad notch --
and X2 as two bottom-side header housings), so the DRC rule and the gate see the same parts. Heights are the
datasheet maximum seated heights in tools/body_heights.json (sources per part there).

Every body goes on Mechanical 13 (unused on this board), projected to the part's own side (X2's housings to the
Bottom), standoff 0. PlaceBodies refuses unless asar_feather.PcbDoc is focused and the board has no component body
yet. No body by design: the Creative Commons artwork (off the board) and the JTAG test pads JP3/JP4.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import body_check  # noqa: E402

MODEL = os.path.join(HERE, 'route', 'body_gate', 'model.json')
COMPS = os.path.join(HERE, 'route', 'body_gate', 'comps.json')
HEIGHTS = os.path.join(HERE, 'body_heights.json')
EXEMPT = {'CC_BY', 'CC_CC', 'CC_COPYRIGHT', 'CC_SA', 'TP-1X03-SMD'}
NAME = 'AsarBodies3D'


def bodies():
    M, D = json.load(open(MODEL)), json.load(open(COMPS))
    H = json.load(open(HEIGHTS))['height_max_mm']
    side = {c['ref']: c['layer'] for c in D['comps']}
    pat = {c['ref']: c['pattern'] for c in D['comps']}
    out, missing = [], []
    bad = body_check.mech_mismatch(D)
    if bad:
        raise SystemExit('; '.join(bad))
    for s, parts in body_check.build(M, D).items():
        for ref, v in sorted(parts.items()):
            if not v['body']:
                continue
            base = ref.split('[')[0]
            if base == 'X2':                       # the two header housings, on the Bottom
                p = pat['X2']
            else:
                if side[base] != ('TOP' if s == 'Top' else 'BOTTOM'):
                    continue
                p = pat[base]
            if p in EXEMPT:
                continue
            if p not in H:
                missing.append(p)
                continue
            for k, b in enumerate(v['body']):
                out.append(dict(ref=base, part=ref if len(v['body']) == 1 else '%s#%d' % (ref, k + 1), pattern=p,
                                bottom=(s == 'Bottom'), x0=b[0], y0=b[1], x1=b[2], y1=b[3], h=H[p]))
    if missing:
        raise SystemExit('no height for: %s (add to tools/body_heights.json)' % ', '.join(sorted(set(missing))))
    refs = {c['ref'] for c in D['comps'] if c['pattern'] not in EXEMPT}
    have = {b['ref'] for b in out}
    if refs - have:
        raise SystemExit('parts without a body: %s' % ', '.join(sorted(refs - have)))
    return out


def main():
    B = bodies()
    os.makedirs(os.path.join(HERE, 'route', 'bodies3d'), exist_ok=True)
    json.dump(B, open(os.path.join(HERE, 'route', 'bodies3d', 'bodies.json'), 'w'), indent=1)
    refs = sorted({b['ref'] for b in B})
    L = ['{ %s.pas -- GENERATED by tools/emit_bodies.py; do not edit by hand.' % NAME,
         '  %d extruded 3D bodies (Mechanical 13) on %d parts. Run PlaceBodies with asar_feather.PcbDoc focused, then save. }' % (
             len(B), len(refs)), '',
         'Procedure AddBody(Brd : IPCB_Board; Ref : String; X0, Y0, X1, Y1, H : Double; Bot : Boolean);',
         'Var', '    Cm : IPCB_Component;', '    B  : IPCB_ComponentBody;', '    Ct : IPCB_Contour;', '    Md : IPCB_Model;',
         'Begin', '    Cm := Brd.GetPcbComponentByRefDes(Ref);',
         '    B := PCBServer.PCBObjectFactory(eComponentBodyObject, eNoDimension, eCreate_Default);',
         '    Ct := PCBServer.PCBContourFactory;',
         '    Ct.AddPoint(Brd.XOrigin + MMsToCoord(X0), Brd.YOrigin + MMsToCoord(Y0));',
         '    Ct.AddPoint(Brd.XOrigin + MMsToCoord(X1), Brd.YOrigin + MMsToCoord(Y0));',
         '    Ct.AddPoint(Brd.XOrigin + MMsToCoord(X1), Brd.YOrigin + MMsToCoord(Y1));',
         '    Ct.AddPoint(Brd.XOrigin + MMsToCoord(X0), Brd.YOrigin + MMsToCoord(Y1));',
         '    B.SetOutlineContour(Ct);', '    B.Layer := eMechanical13;',
         '    If Bot Then B.BodyProjection := eBoardSide_Bottom Else B.BodyProjection := eBoardSide_Top;',
         '    Md := B.ModelFactory_CreateExtruded(0, MMsToCoord(H), $808080);', '    B.SetModel(Md);',
         '    Cm.AddPCBObject(B);', '    Brd.AddPCBObject(B);', 'End;', '',
         'Procedure PlaceBodies;', 'Var', '    Brd : IPCB_Board;', '    It : IPCB_BoardIterator;', '    n : Integer;',
         '    Missing : String;', 'Begin', '    Brd := PCBServer.GetCurrentPCBBoard;',
         "    If (Brd = Nil) Or (Pos('asar_feather.PcbDoc', Brd.FileName) = 0) Then", '    Begin',
         "        ShowMessage('Refusing: focus asar_feather.PcbDoc first.');", '        Exit;', '    End;',
         '    n := 0;', '    It := Brd.BoardIterator_Create;', '    It.AddFilter_ObjectSet(MkSet(eComponentBodyObject));',
         '    It.AddFilter_LayerSet(AllLayers);', '    It.AddFilter_Method(eProcessAll);',
         '    If It.FirstPCBObject <> Nil Then n := 1;', '    Brd.BoardIterator_Destroy(It);', '    If n > 0 Then', '    Begin',
         "        ShowMessage('Refusing: the board already has component bodies; reload it from disk first.');", '        Exit;', '    End;',
         "    Missing := '';"]
    for r in refs:
        L.append("    If Brd.GetPcbComponentByRefDes('%s') = Nil Then Missing := Missing + ' %s';" % (r, r))
    L += ["    If Missing <> '' Then", '    Begin', "        ShowMessage('Refusing: parts not on the board:' + Missing);",
          '        Exit;', '    End;', '    PCBServer.PreProcess;']
    for b in B:
        L.append("    AddBody(Brd, '%s', %.4f, %.4f, %.4f, %.4f, %.3f, %s);   { %s %s }" % (
            b['ref'], b['x0'], b['y0'], b['x1'], b['y1'], b['h'], 'True' if b['bottom'] else 'False', b['part'], b['pattern']))
    L += ['    PCBServer.PostProcess;', '    Brd.ViewManager_FullUpdate;',
          "    ShowMessage('%d bodies placed on %d parts (Mechanical 13). Save the board.');" % (len(B), len(refs)), 'End;', '']
    open(os.path.join(HERE, NAME + '.pas'), 'w', newline='\r\n').write('\n'.join(L))
    open(os.path.join(HERE, NAME + '.PrjScr'), 'w', newline='\n').write(
        '[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=%s.pas\n' % NAME)
    print('%d bodies on %d parts -> tools/%s.pas' % (len(B), len(refs), NAME))


if __name__ == '__main__':
    main()

"""Emit tools/AsarNpthClear.pas from tools/route/npth_clearance/plan.json (2026-11-16).

Two procedures, run with asar_feather.PcbDoc focused:
  AddNpthTrackRule   adds Clearance_NPTH_Track: tracks / vias / arcs to the X1 and X2 non-plated holes >= 0.127 mm
                     (PCBWay 2026-11-16: through hole to trace >= 5 mil). Scope 1 leaves the plane polygons out, so
                     Clearance_Plane_NPTH (0.25 mm) still governs the pours whatever priority the new rule gets.
                     Run DRC after it: the old tracks must show up as violations (proof the scope matches).
  NpthClearFix       removes the five track runs of the plan and lays the new ones. All or nothing: every old segment
                     must be found exactly once, and the nets must exist, or nothing changes.
    python tools/emit_npth_clearance.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PLAN = os.path.join(HERE, 'route', 'npth_clearance', 'plan.json')
OUT = os.path.join(HERE, 'AsarNpthClear.pas')
LAYER = {'Top': 'eTopLayer', 'L3-SIG': 'eMidLayer1', 'L4-SIG': 'eMidLayer2', 'Bottom': 'eBottomLayer'}


def f(v):
    return ('%.4f' % v).rstrip('0').rstrip('.')


def main():
    plan = json.load(open(PLAN))
    assert plan['report']['ok'], 'plan is not OK'
    finds, adds, nets = [], [], []
    for e in plan['edits']:
        L = LAYER[e['layer']]
        if e['net'] not in nets:
            nets.append(e['net'])
        old = [p for p in e['old']]
        for a, b in zip(old, old[1:]):
            finds.append("    T := FindTrack('%s', %s, %s, %s, %s, %s); If T <> Nil Then DT.Add(T);"
                         % (e['net'], L, f(a[0]), f(a[1]), f(b[0]), f(b[1])))
        new = e['new']
        for a, b in zip(new, new[1:]):
            adds.append("    AddTrack('%s', %s, %s, %s, %s, %s, %s);" % (e['net'], L, f(a[0]), f(a[1]), f(b[0]), f(b[1]), f(e['width'])))
    netvars = '\n'.join("    If NetByName('%s') = Nil Then Begin Bad := Bad + 1; Msg := Msg + 'no net %s' + #13; End;" % (n, n)
                        for n in nets)
    src = r"""{ AsarNpthClear.pas -- 2026-11-16, generated by tools/emit_npth_clearance.py from tools/route/npth_clearance/plan.json.
  PCBWay (2026-11-16): through hole to trace >= 5 mil. Tracks passed 0.086-0.127 mm from three non-plated holes
  (X1 pegs at (6.2495, 8.54) and (6.2495, 14.32), X2 hole at (2.54, 20.32)).
  Run with asar_feather.PcbDoc focused:
    AddNpthTrackRule  adds Clearance_NPTH_Track (tracks/vias/arcs to X1/X2 NPTH, 0.127 mm); then DRC must flag the old tracks.
    NpthClearFix      removes %(nold)d old segments and lays %(nnew)d new ones (all or nothing). Then DRC, Save. }

Var Brd : IPCB_Board; ox, oy : Integer; Msg : String; Bad : Integer;

Function C(v : Double) : Integer;
Begin
    Result := MMsToCoord(v);
End;

Function NetOf(O : IPCB_Primitive) : String;
Begin
    Result := '';
    If O.Net <> Nil Then Result := O.Net.Name;
End;

Function NetByName(AName : String) : IPCB_Net;
Var It : IPCB_BoardIterator; N : IPCB_Net;
Begin
    Result := Nil;
    It := Brd.BoardIterator_Create; It.AddFilter_ObjectSet(MkSet(eNetObject)); It.AddFilter_LayerSet(AllLayers); It.AddFilter_Method(eProcessAll);
    N := It.FirstPCBObject;
    While N <> Nil Do
    Begin
        If N.Name = AName Then Result := N;
        N := It.NextPCBObject;
    End;
    Brd.BoardIterator_Destroy(It);
End;

Function FindTrack(NetName : String; L : TLayer; X1, Y1, X2, Y2 : Double) : IPCB_Track;
Var It : IPCB_BoardIterator; T : IPCB_Track; n : Integer;
Begin
    Result := Nil; n := 0;
    It := Brd.BoardIterator_Create; It.AddFilter_ObjectSet(MkSet(eTrackObject)); It.AddFilter_LayerSet(MkSet(L)); It.AddFilter_Method(eProcessAll);
    T := It.FirstPCBObject;
    While T <> Nil Do
    Begin
        If (NetOf(T) = NetName) And
           (((Abs(T.X1 - ox - C(X1)) < 30) And (Abs(T.Y1 - oy - C(Y1)) < 30) And (Abs(T.X2 - ox - C(X2)) < 30) And (Abs(T.Y2 - oy - C(Y2)) < 30)) Or
            ((Abs(T.X2 - ox - C(X1)) < 30) And (Abs(T.Y2 - oy - C(Y1)) < 30) And (Abs(T.X1 - ox - C(X2)) < 30) And (Abs(T.Y1 - oy - C(Y2)) < 30))) Then
        Begin Result := T; n := n + 1; End;
        T := It.NextPCBObject;
    End;
    Brd.BoardIterator_Destroy(It);
    If n <> 1 Then Begin Result := Nil; Bad := Bad + 1; Msg := Msg + 'track ' + NetName + ' ' + FloatToStr(X1) + ',' + FloatToStr(Y1) + ' found ' + IntToStr(n) + #13; End;
End;

Procedure AddTrack(NetName : String; L : TLayer; X1, Y1, X2, Y2, W : Double);
Var T : IPCB_Track; N : IPCB_Net;
Begin
    N := NetByName(NetName);
    T := PCBServer.PCBObjectFactory(eTrackObject, eNoDimension, eCreate_Default);
    T.X1 := ox + C(X1); T.Y1 := oy + C(Y1); T.X2 := ox + C(X2); T.Y2 := oy + C(Y2); T.Width := C(W); T.Layer := L;
    T.Net := N; Brd.AddPCBObject(T); N.AddPCBObject(T);
End;

Function FindRule(Name : String) : IPCB_Rule;
Var It : IPCB_BoardIterator; R : IPCB_Rule;
Begin
    Result := Nil;
    It := Brd.BoardIterator_Create; It.AddFilter_ObjectSet(MkSet(eRuleObject)); It.AddFilter_LayerSet(AllLayers); It.AddFilter_Method(eProcessAll);
    R := It.FirstPCBObject;
    While R <> Nil Do
    Begin
        If R.Name = Name Then Result := R;
        R := It.NextPCBObject;
    End;
    Brd.BoardIterator_Destroy(It);
End;

Function Focus : Boolean;
Begin
    Result := False;
    Brd := PCBServer.GetCurrentPCBBoard; If Brd = Nil Then Exit;
    If Pos('\Rev_1\Asar_feather.PrjPcb\asar_feather.PcbDoc', Brd.FileName) = 0 Then Begin ShowMessage('Refusing: focus Asar_feather\Rev_1\...\asar_feather.PcbDoc'); Exit; End;
    ox := Brd.XOrigin; oy := Brd.YOrigin; Msg := ''; Bad := 0;
    Result := True;
End;

Procedure AddNpthTrackRule;
Var R : IPCB_Rule;
Begin
    If Not Focus Then Exit;
    If FindRule('Clearance_NPTH_Track') <> Nil Then Begin ShowMessage('Clearance_NPTH_Track exists; nothing changed.'); Exit; End;
    PCBServer.PreProcess;
    R := PCBServer.PCBRuleFactory(eRule_Clearance);
    R.Name := 'Clearance_NPTH_Track';
    R.Scope1Expression := '(IsTrack Or IsVia Or IsArc)';
    R.Scope2Expression := 'IsPad And ((Name = ''X2-'') Or (Name = ''X1-''))';
    R.NetScope := eNetScope_AnyNet;
    R.LayerKind := eRuleLayerKind_SameLayer;
    R.Gap := MMsToCoord(0.127);
    Brd.AddPCBObject(R);
    PCBServer.PostProcess;
    ShowMessage('Clearance_NPTH_Track added: gap ' + FloatToStr(CoordToMMs(R.Gap)) + ' mm, priority ' + IntToStr(R.Priority) + '. Run DRC now: the old tracks must be flagged.');
End;

Procedure NpthClearFix;
Var DT : TInterfaceList; T : IPCB_Track; i : Integer;
Begin
    If Not Focus Then Exit;
    DT := TInterfaceList.Create;
%(finds)s
%(netvars)s
    If Bad > 0 Then Begin ShowMessage('Refusing, nothing changed:' + #13 + Msg); Exit; End;
    If DT.Count <> %(nold)d Then Begin ShowMessage('Refusing: found ' + IntToStr(DT.Count) + ' of %(nold)d segments; nothing changed.'); Exit; End;
    PCBServer.PreProcess;
    For i := 0 To DT.Count - 1 Do Brd.RemovePCBObject(DT.Items[i]);
%(adds)s
    PCBServer.PostProcess; Brd.ViewManager_FullUpdate;
    ShowMessage('NPTH clearance: removed ' + IntToStr(DT.Count) + ' segments, added %(nnew)d. Run DRC, then Save.');
End;
""" % dict(finds='\n'.join(finds), adds='\n'.join(adds), netvars=netvars, nold=len(finds), nnew=len(adds))
    open(OUT, 'w', newline='\r\n').write(src)
    open(OUT.replace('.pas', '.PrjScr'), 'w', newline='\r\n').write('[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=AsarNpthClear.pas\n')
    print('wrote %s: %d removals, %d additions, nets %s' % (OUT, len(finds), len(adds), nets))


if __name__ == '__main__':
    main()

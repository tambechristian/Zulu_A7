"""Turn a large copper delta (remove / remove_vias / tracks / vias, as written by route/x4_feasibility/qfn/live_delta.py)
into a table-driven DelphiScript. emit_copper.py tests every track of the board against every removal line, which is
too slow for ~1000 removals; here each board object is reduced to a key string and looked up in a sorted list.

    python tools/emit_delta.py <plan.json> <Name>        writes tools/FabBCopper_<Name>.pas/.PrjScr

Procedure Place<Name> refuses unless Zulu_a7_no_pmod.PcbDoc is focused, every net it needs exists, and EVERY removal key
selects exactly one board object (a missing or duplicated object changes nothing). Keys are board-relative integers in
0.1 um: tracks net|layer|width|x1|y1|x2|y2 (ends ordered), vias net|x|y|hole|size|upper|lower. Layer codes: T, 2 (L2-GND),
3 (L3-SIG), 4 (L4-SIG), 5 (L5-VCC3V3), B. Additions use the V/T helpers of emit_copper.py. The removals run first, then the
additions in chunks of procedures (a single procedure of thousands of statements is avoided on purpose).
"""
import json
import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
LAYER = {'Top Layer': 'eTopLayer', 'L2-GND': 'eMidLayer3', 'L3-SIG': 'eMidLayer1', 'L4-SIG': 'eMidLayer2',
         'L5-VCC3V3': 'eMidLayer4', 'Bottom Layer': 'eBottomLayer'}
CODE = {'Top Layer': 'T', 'L2-GND': '2', 'L3-SIG': '3', 'L4-SIG': '4', 'L5-VCC3V3': '5', 'Bottom Layer': 'B'}
CHUNK = 120


def u(x):
    return int(round(x * 10000))


def q(s):
    return s.replace("'", "''")


def tkey(t):
    a, b, c, d = u(t['x1']), u(t['y1']), u(t['x2']), u(t['y2'])
    if a > c or (a == c and b > d):
        a, b, c, d = c, d, a, b
    return '%s|%s|%d|%d|%d|%d|%d' % (t['net'], CODE[t['layer']], u(t['w']), a, b, c, d)


def vkey(v):
    sp = v['span'] if 'span' in v else [v['from'], v['to']]
    return '%s|%d|%d|%d|%d|%s|%s' % (v['net'], u(v['x']), u(v['y']), u(v['hole']), u(v['size']), CODE[sp[0]], CODE[sp[-1]])


def chunks(seq, n):
    for i in range(0, len(seq), n):
        yield seq[i:i + n]


def main():
    path, name = sys.argv[1], sys.argv[2]
    P = json.load(open(path))
    rt = [tkey(t) for t in P['remove']]
    rv = [vkey(v) for v in P.get('remove_vias', [])]
    assert len(set(rt)) == len(rt) and len(set(rv)) == len(rv), 'duplicate removal keys'
    by = defaultdict(lambda: ([], []))
    for v in P['vias']:
        by[v['net']][0].append(v)
    for t in P['tracks']:
        by[t['net']][1].append(t)
    nets = sorted(set(by) | {k.split('|')[0] for k in rt + rv})
    nets_added = sorted(by)

    L = ['{ FabBCopper_%s.pas -- GENERATED by tools/emit_delta.py from %s; do not edit by hand.' % (
        name, os.path.basename(path)),
        '  remove %d tracks + %d vias, then add %d vias + %d tracks on %d nets. Run Place%s with' % (
            len(rt), len(rv), len(P['vias']), len(P['tracks']), len(nets_added), name),
        '  Zulu_a7_no_pmod.PcbDoc focused (the removal keys must all be found first), then save only the PCB. }', '',
        'Var',
        '    Brd : IPCB_Board;',
        '    Missing : String;',
        '    RT, RV, NN, BN, FT : TStringList;',
        '    Kill, KillV : TInterfaceList;', '',
        'Function NetByName(AName : String) : IPCB_Net;', 'Var', '    It : IPCB_BoardIterator;', '    N  : IPCB_Net;',
        'Begin', '    Result := Nil;', '    It := Brd.BoardIterator_Create;',
        '    It.AddFilter_ObjectSet(MkSet(eNetObject));', '    It.AddFilter_LayerSet(AllLayers);',
        '    It.AddFilter_Method(eProcessAll);', '    N := It.FirstPCBObject;', '    While N <> Nil Do', '    Begin',
        '        If N.Name = AName Then Result := N;', '        N := It.NextPCBObject;', '    End;',
        '    Brd.BoardIterator_Destroy(It);', 'End;', '',
        'Function LN(Ly : TLayer) : String;', 'Begin', "    Result := '?';",
        "    If Ly = eTopLayer Then Result := 'T'",
        "    Else If Ly = eMidLayer3 Then Result := '2'",
        "    Else If Ly = eMidLayer1 Then Result := '3'",
        "    Else If Ly = eMidLayer2 Then Result := '4'",
        "    Else If Ly = eMidLayer4 Then Result := '5'",
        "    Else If Ly = eBottomLayer Then Result := 'B';", 'End;', '',
        'Function UM(Cv : TCoord) : Integer;', 'Begin', '    Result := Round(CoordToMMs(Cv) * 10000);', 'End;', '',
        'Function TrackKey(K : IPCB_Track) : String;', 'Var', '    nm : String;', '    a, b, c, d, tmp : Integer;', 'Begin',
        "    nm := '';", '    If K.Net <> Nil Then nm := K.Net.Name;',
        '    a := UM(K.X1 - Brd.XOrigin); b := UM(K.Y1 - Brd.YOrigin);',
        '    c := UM(K.X2 - Brd.XOrigin); d := UM(K.Y2 - Brd.YOrigin);',
        '    If (a > c) Or ((a = c) And (b > d)) Then',
        '    Begin', '        tmp := a; a := c; c := tmp;', '        tmp := b; b := d; d := tmp;', '    End;',
        "    Result := nm + '|' + LN(K.Layer) + '|' + IntToStr(UM(K.Width)) + '|' + IntToStr(a) + '|' + IntToStr(b) + '|' + IntToStr(c) + '|' + IntToStr(d);",
        'End;', '',
        'Function ViaKey(K : IPCB_Via) : String;', 'Var', '    nm : String;', 'Begin',
        "    nm := '';", '    If K.Net <> Nil Then nm := K.Net.Name;',
        "    Result := nm + '|' + IntToStr(UM(K.X - Brd.XOrigin)) + '|' + IntToStr(UM(K.Y - Brd.YOrigin)) + '|' + IntToStr(UM(K.HoleSize)) + '|' + IntToStr(UM(K.Size)) + '|' + LN(K.LowLayer) + '|' + LN(K.HighLayer);",
        'End;', '',
        'Procedure V(N : IPCB_Net; X, Y, S, H : Double; Lo, Hi : TLayer);', 'Var', '    O : IPCB_Via;', 'Begin',
        '    O := PCBServer.PCBObjectFactory(eViaObject, eNoDimension, eCreate_Default);',
        '    O.X := Brd.XOrigin + MMsToCoord(X); O.Y := Brd.YOrigin + MMsToCoord(Y);',
        '    O.Size := MMsToCoord(S); O.HoleSize := MMsToCoord(H);',
        '    O.LowLayer := Lo; O.HighLayer := Hi;',
        '    O.Net := N; Brd.AddPCBObject(O); N.AddPCBObject(O);', 'End;', '',
        'Procedure T(N : IPCB_Net; L : TLayer; W, X1, Y1, X2, Y2 : Double);', 'Var', '    O : IPCB_Track;', 'Begin',
        '    O := PCBServer.PCBObjectFactory(eTrackObject, eNoDimension, eCreate_Default);',
        '    O.X1 := Brd.XOrigin + MMsToCoord(X1); O.Y1 := Brd.YOrigin + MMsToCoord(Y1);',
        '    O.X2 := Brd.XOrigin + MMsToCoord(X2); O.Y2 := Brd.YOrigin + MMsToCoord(Y2);',
        '    O.Layer := L; O.Width := MMsToCoord(W); O.Net := N; Brd.AddPCBObject(O);', 'End;', '']

    def table(proc, lst, items):
        out = []
        for i, part in enumerate(chunks(items, CHUNK)):
            out += ['Procedure %s%d;' % (proc, i + 1), 'Begin'] + ["    %s.Add('%s');" % (lst, q(k)) for k in part] + ['End;', '']
        n = (len(items) + CHUNK - 1) // CHUNK
        out += ['Procedure %sAll;' % proc, 'Begin'] + ['    %s%d;' % (proc, i + 1) for i in range(n)] + ['End;', '']
        return out

    L += table('LoadRT', 'RT', rt)
    L += table('LoadRV', 'RV', rv)
    L += table('LoadNN', 'NN', nets)

    # additions: one procedure per few nets, so no procedure holds more than about CHUNK statements
    parts, cur, cnt = [], [], 0
    for net in nets_added:
        vs, ts = by[net]
        lines = ["    N := NetByName('%s');" % q(net), "    If N = Nil Then Missing := Missing + ' %s' Else" % q(net), '    Begin']
        for v in vs:
            lines.append('        V(N, %.4f, %.4f, %.4f, %.4f, %s, %s);' % (v['x'], v['y'], v['size'], v['hole'], LAYER[v['from']], LAYER[v['to']]))
        for t in ts:
            lines.append('        T(N, %s, %.4f, %.4f, %.4f, %.4f, %.4f);' % (LAYER[t['layer']], t['w'], t['x1'], t['y1'], t['x2'], t['y2']))
        lines.append('    End;')
        if cur and cnt + len(lines) > CHUNK:
            parts.append(cur)
            cur, cnt = [], 0
        cur += lines
        cnt += len(lines)
    if cur:
        parts.append(cur)
    for i, ln in enumerate(parts):
        L += ['Procedure AddPart%d;' % (i + 1), 'Var', '    N : IPCB_Net;', 'Begin'] + ln + ['End;', '']
    L += ['Procedure AddAll;', 'Begin'] + ['    AddPart%d;' % (i + 1) for i in range(len(parts))] + ['End;', '']

    guard = "    If (Pos('\\Zulu_A7_no_pmod\\Rev_4\\Imported zulu_a7.PrjPcb\\Zulu_a7_no_pmod.PcbDoc', Doc.DM_FullPath) = 0) Then"
    L += [
        'Procedure Place%s;' % name, 'Var',
        '    Doc : IDocument;', '    It : IPCB_BoardIterator;', '    K : IPCB_Track;', '    KV : IPCB_Via;', '    N : IPCB_Net;',
        '    i : Integer;', '    Msg : String;', 'Begin',
        '    Doc := GetWorkspace.DM_FocusedDocument;',
        '    If Doc = Nil Then Exit;', guard, '    Begin',
        "        ShowMessage('Refusing: focus Zulu_A7_no_pmod\\Rev_4\\Imported zulu_a7.PrjPcb\\Zulu_a7_no_pmod.PcbDoc first.');",
        '        Exit;', '    End;', '    Brd := PCBServer.GetCurrentPCBBoard;',
        '    RT := TStringList.Create; RV := TStringList.Create; NN := TStringList.Create;',
        '    BN := TStringList.Create; FT := TStringList.Create;',
        '    RT.Sorted := True; RV.Sorted := True; BN.Sorted := True; FT.Sorted := True;',
        '    LoadRTAll; LoadRVAll; LoadNNAll;',
        "    Missing := '';",
        # every net the plan names must exist
        '    It := Brd.BoardIterator_Create;', '    It.AddFilter_ObjectSet(MkSet(eNetObject));',
        '    It.AddFilter_LayerSet(AllLayers);', '    It.AddFilter_Method(eProcessAll);', '    N := It.FirstPCBObject;',
        '    While N <> Nil Do', '    Begin', '        BN.Add(N.Name);', '        N := It.NextPCBObject;', '    End;',
        '    Brd.BoardIterator_Destroy(It);',
        '    For i := 0 To NN.Count - 1 Do',
        "        If BN.IndexOf(NN.Strings[i]) < 0 Then Missing := Missing + ' ' + NN.Strings[i];",
        "    If Missing <> '' Then",
        '    Begin',
        "        ShowMessage('Refusing: nets missing from the board:' + Missing + '. Nothing changed.');",
        '        Exit;', '    End;',
        # find every removal first
        '    Kill := TInterfaceList.Create; KillV := TInterfaceList.Create;',
        '    It := Brd.BoardIterator_Create;', '    It.AddFilter_ObjectSet(MkSet(eTrackObject));',
        '    It.AddFilter_LayerSet(AllLayers);', '    It.AddFilter_Method(eProcessAll);', '    K := It.FirstPCBObject;',
        '    While K <> Nil Do', '    Begin',
        '        If RT.IndexOf(TrackKey(K)) >= 0 Then', '        Begin', '            Kill.Add(K);', '            FT.Add(TrackKey(K));', '        End;',
        '        K := It.NextPCBObject;', '    End;', '    Brd.BoardIterator_Destroy(It);',
        '    It := Brd.BoardIterator_Create;', '    It.AddFilter_ObjectSet(MkSet(eViaObject));',
        '    It.AddFilter_LayerSet(AllLayers);', '    It.AddFilter_Method(eProcessAll);', '    KV := It.FirstPCBObject;',
        '    While KV <> Nil Do', '    Begin',
        '        If RV.IndexOf(ViaKey(KV)) >= 0 Then', '        Begin', '            KillV.Add(KV);', '            FT.Add(ViaKey(KV));', '        End;',
        '        KV := It.NextPCBObject;', '    End;', '    Brd.BoardIterator_Destroy(It);',
        '    If (Kill.Count <> RT.Count) Or (KillV.Count <> RV.Count) Then',
        '    Begin',
        "        Msg := 'Refusing: found ' + IntToStr(Kill.Count) + ' of ' + IntToStr(RT.Count) + ' tracks and ' + IntToStr(KillV.Count) + ' of ' + IntToStr(RV.Count) + ' vias to remove. Nothing changed.';",
        '        For i := 0 To RT.Count - 1 Do',
        '            If FT.IndexOf(RT.Strings[i]) < 0 Then Msg := Msg + Chr(10) + RT.Strings[i];',
        '        For i := 0 To RV.Count - 1 Do',
        '            If FT.IndexOf(RV.Strings[i]) < 0 Then Msg := Msg + Chr(10) + RV.Strings[i];',
        '        ShowMessage(Msg);',
        '        Exit;', '    End;',
        '    For i := 0 To KillV.Count - 1 Do Brd.RemovePCBObject(KillV.Items[i]);',
        '    For i := 0 To Kill.Count - 1 Do Brd.RemovePCBObject(Kill.Items[i]);',
        '    AddAll;',
        '    Brd.ViewManager_FullUpdate;',
        "    ShowMessage('Removed ' + IntToStr(RT.Count) + ' tracks and ' + IntToStr(RV.Count) + ' vias, placed %d vias and %d tracks. Missing nets:' + Missing + '. Save only the PCB, then mark microvias.');" % (
            len(P['vias']), len(P['tracks'])),
        'End;', '']
    out =  os.path.join(HERE, 'FabBCopper_%s.pas' % name)
    open(out, 'w', newline='\n').write('\n'.join(L))
    open(os.path.join(HERE, 'FabBCopper_%s.PrjScr' % name), 'w', newline='\n').write(
        '[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=FabBCopper_%s.pas\n' % name)
    print('%s: remove %d tracks + %d vias; add %d vias + %d tracks; %d nets; %d lines' % (
        os.path.relpath(out), len(rt), len(rv), len(P['vias']), len(P['tracks']), len(nets_added), len(L)))


if __name__ == '__main__':
    main()

"""Turn a routing plan (tools/route/<stage>.json: {vias: [...], tracks: [...]}) into a DelphiScript that places it.

    python tools/emit_copper.py tools/route/stage1_u1.json Stage1U1     writes tools/FabBCopper_Stage1U1.pas/.PrjScr

The procedure Place<Name> refuses to run unless zulu_a7_fab_b.PcbDoc is focused and the board holds no copper of
this plan yet (it counts vias at the plan's first via position). A plan's 'remove' tracks and 'remove_vias' are deleted first,
and only if every one of them is found. Coordinates are board-relative mm, added to the
board origin. Layer mapping as on production (tools/stage13 in Zulu_Altium_VS_Code): Top eTopLayer, L2-GND
eMidLayer3, L3-SIG eMidLayer1, L4-SIG eMidLayer2, L5-VCC3V3 eMidLayer4, Bottom eBottomLayer; a via's LowLayer is
its upper layer. Vias join their net with N.AddPCBObject as well (production practice); tracks take T.Net.
Scripted laser vias are regular blind vias until tools/mark_microvias.py marks them in the saved file.
"""
import json
import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
LAYER = {'Top Layer': 'eTopLayer', 'L2-GND': 'eMidLayer3', 'L3-SIG': 'eMidLayer1', 'L4-SIG': 'eMidLayer2',
         'L5-VCC3V3': 'eMidLayer4', 'Bottom Layer': 'eBottomLayer'}


def main():
    path, name = sys.argv[1], sys.argv[2]
    P = json.load(open(path))
    by = defaultdict(lambda: ([], []))
    for v in P['vias']:
        by[v['net']][0].append(v)
    for t in P['tracks']:
        by[t['net']][1].append(t)
    # a delta that only swaps tracks has no via: the remove guard (every track found) protects it instead
    rmv = P.get('remove_vias', [])
    free = [v for v in P['vias'] if not any(abs(v['x'] - r['x']) < 0.02 and abs(v['y'] - r['y']) < 0.02 for r in rmv)]
    v0 = free[0] if free else {'x': -1000.0, 'y': -1000.0}   # guard via: one not sitting where a ripped via was
    L = ['{ FabBCopper_%s.pas -- GENERATED by tools/emit_copper.py from %s; do not edit by hand.' % (
        name, os.path.relpath(path, os.path.dirname(HERE)).replace('\\', '/')),
        '  %d vias, %d tracks on %d nets. Run Place%s with zulu_a7_fab_b.PcbDoc focused, then save. }' % (
            len(P['vias']), len(P['tracks']), len(by), name), '',
        'Var', '    Brd : IPCB_Board;', '',
        'Function NetByName(AName : String) : IPCB_Net;', 'Var', '    It : IPCB_BoardIterator;', '    N  : IPCB_Net;',
        'Begin', '    Result := Nil;', '    It := Brd.BoardIterator_Create;',
        '    It.AddFilter_ObjectSet(MkSet(eNetObject));', '    It.AddFilter_LayerSet(AllLayers);',
        '    It.AddFilter_Method(eProcessAll);', '    N := It.FirstPCBObject;', '    While N <> Nil Do', '    Begin',
        '        If N.Name = AName Then Result := N;', '        N := It.NextPCBObject;', '    End;',
        '    Brd.BoardIterator_Destroy(It);', 'End;', '',
        'Procedure V(N : IPCB_Net; X, Y, S, H : Double; Lo, Hi : TLayer);', 'Var', '    O : IPCB_Via;', 'Begin',
        '    O := PCBServer.PCBObjectFactory(eViaObject, eNoDimension, eCreate_Default);',
        '    O.X := Brd.XOrigin + MMsToCoord(X); O.Y := Brd.YOrigin + MMsToCoord(Y);',
        '    O.Size := MMsToCoord(S); O.HoleSize := MMsToCoord(H);',
        '    O.LowLayer := Lo; O.HighLayer := Hi;',
        '    O.Net := N; Brd.AddPCBObject(O); N.AddPCBObject(O);', 'End;', '',
        'Procedure T(N : IPCB_Net; L : TLayer; W, X1, Y1, X2, Y2 : Double);', 'Var', '    O : IPCB_Track;', 'Begin',
        '    O := PCBServer.PCBObjectFactory(eTrackObject, eNoDimension, eCreate_Default);',
        '    O.X1 := Brd.XOrigin + MMsToCoord(X1); O.Y1 := Brd.YOrigin + MMsToCoord(Y1);',
        '    O.X2 := Brd.XOrigin + MMsToCoord(X2); O.Y2 := Brd.YOrigin + MMsToCoord(Y2);',
        '    O.Layer := L; O.Width := MMsToCoord(W); O.Net := N; Brd.AddPCBObject(O);', 'End;', '',
        'Procedure Place%s;' % name, 'Var', '    Doc : IDocument;', '    N : IPCB_Net;', '    It : IPCB_BoardIterator;',
        '    O : IPCB_Via;', '    Missing : String;', 'Begin',
        '    Doc := GetWorkspace.DM_FocusedDocument;',
        "    If (Doc = Nil) Or (Pos('\\Zulu_A7_Fab_B\\Imported zulu_a7.PrjPcb\\zulu_a7_fab_b.PcbDoc', Doc.DM_FullPath) = 0) Then",
        '    Begin', "        ShowMessage('Refusing: focus Zulu_A7_Fab_B\\Imported zulu_a7.PrjPcb\\zulu_a7_fab_b.PcbDoc first.');",
        '        Exit;', '    End;', '    Brd := PCBServer.GetCurrentPCBBoard;',
        '    It := Brd.BoardIterator_Create;', '    It.AddFilter_ObjectSet(MkSet(eViaObject));',
        '    It.AddFilter_LayerSet(AllLayers);', '    It.AddFilter_Method(eProcessAll);', '    O := It.FirstPCBObject;',
        '    While O <> Nil Do', '    Begin',
        '        If (Abs(O.X - Brd.XOrigin - MMsToCoord(%.4f)) < 300) And (Abs(O.Y - Brd.YOrigin - MMsToCoord(%.4f)) < 300) Then' % (
            v0['x'], v0['y']),
        '        Begin', '            Brd.BoardIterator_Destroy(It);',
        "            ShowMessage('Refusing: this plan''s first via is already on the board.');", '            Exit;',
        '        End;', '        O := It.NextPCBObject;', '    End;', '    Brd.BoardIterator_Destroy(It);',
        "    Missing := '';"]
    mv = P.get('moves', [])
    if mv:
        # component moves (Fab B LED spread): every part must be found at its old place before anything changes;
        # the move itself runs after the removals, before the new copper
        for m in mv:
            L += ["    Cm := Brd.GetPcbComponentByRefDes('%s');" % m['ref'],
                  '    If (Cm = Nil) Or (Abs(CoordToMMs(Cm.Y - Brd.YOrigin) - %.4f) > 0.002) Or (Abs(CoordToMMs(Cm.X - Brd.XOrigin) - %.4f) > 0.002) Then' % (
                      m['y'] - m.get('dy', 0), m['x'] - m.get('dx', 0)),
                  '    Begin', "        ShowMessage('Refusing: %s is missing or not at (%.4f, %.4f); nothing changed.');" % (
                      m['ref'], m['x'] - m.get('dx', 0), m['y'] - m.get('dy', 0)), '        Exit;', '    End;']
    rm = P.get('remove', [])
    if rm:
        # the plan's 'remove' tracks go first: all of them must be found (net, layer, width, ends either way round
        # within 0.002 mm), or nothing at all is changed
        L += ['    Kill := TInterfaceList.Create;', '    It := Brd.BoardIterator_Create;',
              '    It.AddFilter_ObjectSet(MkSet(eTrackObject));', '    It.AddFilter_LayerSet(AllLayers);',
              '    It.AddFilter_Method(eProcessAll);', '    K := It.FirstPCBObject;', '    While K <> Nil Do', '    Begin',
              "        nm := ''; If K.Net <> Nil Then nm := K.Net.Name;",
              '        x := CoordToMMs(K.X1 - Brd.XOrigin); y := CoordToMMs(K.Y1 - Brd.YOrigin);',
              '        x2 := CoordToMMs(K.X2 - Brd.XOrigin); y2 := CoordToMMs(K.Y2 - Brd.YOrigin);',
              '        tw := CoordToMMs(K.Width);']
        for t in rm:
            a = '(Abs(x - %.4f) < 0.002) And (Abs(y - %.4f) < 0.002) And (Abs(x2 - %.4f) < 0.002) And (Abs(y2 - %.4f) < 0.002)'
            L.append("        If (nm = '%s') And (K.Layer = %s) And (Abs(tw - %.4f) < 0.002) And ((%s) Or (%s)) Then Kill.Add(K);" % (
                t['net'], LAYER[t['layer']], t['w'], a % (t['x1'], t['y1'], t['x2'], t['y2']),
                a % (t['x2'], t['y2'], t['x1'], t['y1'])))
        L += ['        K := It.NextPCBObject;', '    End;', '    Brd.BoardIterator_Destroy(It);',
              '    If Kill.Count <> %d Then' % len(rm), '    Begin',
              "        ShowMessage('Refusing: found ' + IntToStr(Kill.Count) + ' of the %d tracks to remove; nothing changed.');" % len(rm),
              '        Kill.Free;', '        Exit;', '    End;']
        if not P.get('remove_vias'):      # with vias to remove too, nothing is removed until both lists are complete
            L += ['    For i := 0 To Kill.Count - 1 Do Brd.RemovePCBObject(Kill.Items[i]);', '    Kill.Free;']
        L[L.index('    Missing : String;')] = ('    Missing : String;\n    Kill : TInterfaceList;\n    K : IPCB_Track;\n'
                                                 '    i : Integer;\n    nm : String;\n    x, y, x2, y2, tw : Double;')
    rmv = P.get('remove_vias', [])
    if rmv:
        # the plan's 'remove_vias' go next: every one must be found (net, hole, centre within 0.002 mm)
        L += ['    KillV := TInterfaceList.Create;', '    It := Brd.BoardIterator_Create;',
              '    It.AddFilter_ObjectSet(MkSet(eViaObject));', '    It.AddFilter_LayerSet(AllLayers);',
              '    It.AddFilter_Method(eProcessAll);', '    KV := It.FirstPCBObject;', '    While KV <> Nil Do', '    Begin',
              "        nm := ''; If KV.Net <> Nil Then nm := KV.Net.Name;",
              '        x := CoordToMMs(KV.X - Brd.XOrigin); y := CoordToMMs(KV.Y - Brd.YOrigin);',
              '        tw := CoordToMMs(KV.HoleSize); hit := False;']
        # a stacked column has two vias at one point: each board via is added once, whichever lines it matches
        for v in rmv:
            sp = v['span'] if 'span' in v else [v['from'], v['to']]   # match the span too: a stack is several vias at one point
            L.append("        If (nm = '%s') And (Abs(tw - %.4f) < 0.002) And (Abs(x - %.4f) < 0.002) And (Abs(y - %.4f) < 0.002) And (KV.LowLayer = %s) And (KV.HighLayer = %s) Then hit := True;" % (
                v['net'].replace("'", "''"), v['hole'], v['x'], v['y'], LAYER[sp[0]], LAYER[sp[-1]]))
        L += ['        If hit Then KillV.Add(KV);',
              '        KV := It.NextPCBObject;', '    End;', '    Brd.BoardIterator_Destroy(It);',
              '    If KillV.Count <> %d Then' % len(rmv), '    Begin',
              "        ShowMessage('Refusing: found ' + IntToStr(KillV.Count) + ' of the %d vias to remove; nothing changed.');" % len(rmv),
              '        KillV.Free;'] + (['        Kill.Free;'] if rm else []) + ['        Exit;', '    End;',
              '    For i := 0 To KillV.Count - 1 Do Brd.RemovePCBObject(KillV.Items[i]);', '    KillV.Free;']
        if rm:
            L += ['    For i := 0 To Kill.Count - 1 Do Brd.RemovePCBObject(Kill.Items[i]);', '    Kill.Free;']
        mi = [k for k, l in enumerate(L) if l.startswith('    Missing : String;')][0]
        L[mi] = L[mi] + chr(10).join(['', '    KillV : TInterfaceList;', '    KV : IPCB_Via;', '    hit : Boolean;'] +
                                 ([] if rm else ['    i : Integer;', '    nm : String;', '    x, y, x2, y2, tw : Double;']))
    if mv:
        mi = [k for k, l in enumerate(L) if l.startswith('    Missing : String;')][0]
        L[mi] = L[mi] + chr(10) + '    Cm : IPCB_Component;'
    for m in mv:
        L += ["    Cm := Brd.GetPcbComponentByRefDes('%s');" % m['ref'], '    Cm.BeginModify;',
              '    Cm.X := Cm.X + MMsToCoord(%.4f);' % m.get('dx', 0), '    Cm.Y := Cm.Y + MMsToCoord(%.4f);' % m.get('dy', 0),
              '    Cm.EndModify;']
    for net in sorted(by):
        vs, ts = by[net]
        L.append("    N := NetByName('%s');" % net.replace("'", "''"))
        L.append("    If N = Nil Then Missing := Missing + ' %s' Else" % net.replace("'", "''"))
        L.append('    Begin')
        for v in vs:
            L.append('        V(N, %.4f, %.4f, %.4f, %.4f, %s, %s);' % (v['x'], v['y'], v['size'], v['hole'],
                                                                      LAYER[v['from']], LAYER[v['to']]))
        for t in ts:
            L.append('        T(N, %s, %.4f, %.4f, %.4f, %.4f, %.4f);' % (LAYER[t['layer']], t['w'], t['x1'], t['y1'],
                                                                         t['x2'], t['y2']))
        L.append('    End;')
    L += ['    Brd.ViewManager_FullUpdate;',
          "    ShowMessage('Moved %d parts, removed %d tracks and %d vias, placed %d vias and %d tracks. Missing nets:' + Missing + '. Save, then mark microvias.');" % (
              len(mv), len(rm), len(rmv), len(P['vias']), len(P['tracks'])), 'End;', '']
    out = os.path.join(HERE, 'FabBCopper_%s.pas' % name)
    open(out, 'w', newline='\n').write('\n'.join(L))
    open(os.path.join(HERE, 'FabBCopper_%s.PrjScr' % name), 'w', newline='\n').write(
        '[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=FabBCopper_%s.pas\n' % name)
    print('%s: %d vias, %d tracks, %d nets' % (os.path.relpath(out), len(P['vias']), len(P['tracks']), len(by)))


if __name__ == '__main__':
    main()

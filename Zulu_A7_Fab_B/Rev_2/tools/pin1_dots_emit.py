"""Write tools/FabBPin1Dots.pas from the pin-1 dot plan (tools/route/pin1_dots/marks.json).

The plan (tools/route/pin1_dots/plan_marks.py) puts one silkscreen dot per polarized part: pin 1 (A1 on U1) on the ICs,
Q1, BTN and X4, and the cathode on the LEDs. The script adds each dot as a full-circle arc owned by its component, so it
moves with the part and Design > Make PCB Library carries it into the footprint:

    radius = diameter / 4, line width = diameter / 2  ->  a filled dot of the planned diameter.

Guards in the generated script: the focused document must be this board; every part must be on the planned side with
its reference pad where the plan measured it (0.002 mm); no part may already own an overlay arc at its dot.

    python tools/pin1_dots_emit.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PLAN = os.path.join(HERE, 'route', 'pin1_dots', 'marks.json')
OUT = os.path.join(HERE, 'FabBPin1Dots.pas')


def main():
    plan = json.load(open(PLAN))
    marks = [(ref, m) for ref, m in plan['marks'].items() if m]
    lines = []
    add = lines.append
    add('{ FabBPin1Dots.pas -- generated by tools/pin1_dots_emit.py from tools/route/pin1_dots/marks.json; do not edit.')
    add('  AddPin1Dots: one silkscreen dot per polarized part (pin 1 / A1; LED cathode), owned by the part.')
    add('  RemovePin1Dots: takes them off again (only arcs of exactly the planned size at the planned spots).')
    add('  Run with Zulu_A7_Fab_B\\Rev_2\\Imported zulu_a7.PrjPcb\\zulu_a7_fab_b.PcbDoc focused, then DRC and File > Save. }')
    add('')
    add('Var')
    add('    Brd : IPCB_Board;')
    add('')
    add('Function FindPad(Cm : IPCB_Component; AName : String) : IPCB_Pad;')
    add('Var GI : IPCB_GroupIterator; O : IPCB_Primitive;')
    add('Begin')
    add('    Result := Nil;')
    add('    GI := Cm.GroupIterator_Create;')
    add('    GI.AddFilter_ObjectSet(MkSet(ePadObject));')
    add('    O := GI.FirstPCBObject;')
    add('    While O <> Nil Do')
    add('    Begin')
    add('        If O.Name = AName Then Result := O;')
    add('        O := GI.NextPCBObject;')
    add('    End;')
    add('    Cm.GroupIterator_Destroy(GI);')
    add('End;')
    add('')
    add('Function DotAt(Cm : IPCB_Component; ALayer : TLayer; X, Y, R, W : Double) : IPCB_Arc;')
    add('Var GI : IPCB_GroupIterator; O : IPCB_Primitive;')
    add('Begin')
    add('    Result := Nil;')
    add('    GI := Cm.GroupIterator_Create;')
    add('    GI.AddFilter_ObjectSet(MkSet(eArcObject));')
    add('    O := GI.FirstPCBObject;')
    add('    While O <> Nil Do')
    add('    Begin')
    add('        If (O.Layer = ALayer) And (Abs(CoordToMMs(O.XCenter - Brd.XOrigin) - X) < 0.05) And')
    add('           (Abs(CoordToMMs(O.YCenter - Brd.YOrigin) - Y) < 0.05) Then Result := O;')
    add('        O := GI.NextPCBObject;')
    add('    End;')
    add('    Cm.GroupIterator_Destroy(GI);')
    add('End;')
    add('')
    add('Function Ready(Doc : IDocument) : Boolean;')
    add('Begin')
    add('    Result := False;')
    add("    If (Doc = Nil) Or (Pos('\\Zulu_A7_Fab_B\\Rev_2\\Imported zulu_a7.PrjPcb\\zulu_a7_fab_b.PcbDoc', Doc.DM_FullPath) = 0) Then")
    add('    Begin')
    add("        ShowMessage('Refusing: focus Zulu_A7_Fab_B\\Rev_2\\Imported zulu_a7.PrjPcb\\zulu_a7_fab_b.PcbDoc first.');")
    add('        Exit;')
    add('    End;')
    add('    Brd := PCBServer.GetCurrentPCBBoard;')
    add('    Result := Brd <> Nil;')
    add('End;')
    add('')
    # checks shared by add and remove
    add('Function CheckPart(ARef, APad : String; ATop : Boolean; PX, PY : Double; Var Msg : String) : IPCB_Component;')
    add('Var Cm : IPCB_Component; P : IPCB_Pad;')
    add('Begin')
    add('    Result := Nil;')
    add('    Cm := Brd.GetPcbComponentByRefDes(ARef);')
    add("    If Cm = Nil Then Begin Msg := ARef + ' not found'; Exit; End;")
    add("    If ATop And (Cm.Layer <> eTopLayer) Then Begin Msg := ARef + ' is not on Top'; Exit; End;")
    add("    If (Not ATop) And (Cm.Layer <> eBottomLayer) Then Begin Msg := ARef + ' is not on Bottom'; Exit; End;")
    add('    P := FindPad(Cm, APad);')
    add("    If P = Nil Then Begin Msg := ARef + ' has no pad ' + APad; Exit; End;")
    add('    If (Abs(CoordToMMs(P.X - Brd.XOrigin) - PX) > 0.002) Or (Abs(CoordToMMs(P.Y - Brd.YOrigin) - PY) > 0.002) Then')
    add("    Begin Msg := ARef + '-' + APad + ' is not where the plan measured it'; Exit; End;")
    add('    Result := Cm;')
    add('End;')
    add('')
    for proc in ('AddPin1Dots', 'RemovePin1Dots'):
        adding = proc == 'AddPin1Dots'
        add('Procedure %s;' % proc)
        add('Var')
        add('    Cm : IPCB_Component;')
        add('    A : IPCB_Arc;')
        add('    Msg, Done : String;')
        add('    n, i : Integer;')
        add('    Cms : TInterfaceList;')
        add('Begin')
        add('    If Not Ready(GetWorkspace.DM_FocusedDocument) Then Exit;')
        add("    Msg := ''; Done := ''; n := 0;")
        add('    Cms := TInterfaceList.Create;')
        for ref, m in marks:
            top = 'True' if m['side'] == 'Top' else 'False'
            p = m['check_pad']
            add("    Cm := CheckPart('%s', '%s', %s, %.4f, %.4f, Msg);" % (ref, p['name'], top, p['x'], p['y']))
            add('    If Cm = Nil Then Begin ShowMessage(\'Refusing, nothing changed: \' + Msg); Exit; End;')
            lay = 'eTopOverlay' if m['side'] == 'Top' else 'eBottomOverlay'
            r, w = m['diameter'] / 4, m['diameter'] / 2
            if adding:
                add("    If DotAt(Cm, %s, %.4f, %.4f, %.4f, %.4f) <> Nil Then Begin ShowMessage('Refusing, nothing changed: %s already has a dot'); Exit; End;"
                    % (lay, m['x'], m['y'], r, w, ref))
            add('    Cms.Add(Cm);')
        if adding:
            add('    PCBServer.PreProcess;')
        for i, (ref, m) in enumerate(marks):
            lay = 'eTopOverlay' if m['side'] == 'Top' else 'eBottomOverlay'
            r, w = m['diameter'] / 4, m['diameter'] / 2
            add('    Cm := Cms.Items[%d];' % i)
            if adding:
                add('    A := PCBServer.PCBObjectFactory(eArcObject, eNoDimension, eCreate_Default);')
                add('    A.XCenter := Brd.XOrigin + MMsToCoord(%.4f);' % m['x'])
                add('    A.YCenter := Brd.YOrigin + MMsToCoord(%.4f);' % m['y'])
                add('    A.Radius := MMsToCoord(%.4f);' % r)
                add('    A.LineWidth := MMsToCoord(%.4f);' % w)
                add('    A.StartAngle := 0;')
                add('    A.EndAngle := 360;')
                add('    A.Layer := %s;' % lay)
                add('    Cm.AddPCBObject(A);')
                add('    Brd.AddPCBObject(A);')
                add("    n := n + 1; Done := Done + ' %s';" % ref)
            else:
                add('    A := DotAt(Cm, %s, %.4f, %.4f, %.4f, %.4f);' % (lay, m['x'], m['y'], r, w))
                add('    If (A <> Nil) And (Abs(CoordToMMs(A.Radius) - %.4f) < 0.001) And (Abs(CoordToMMs(A.LineWidth) - %.4f) < 0.001) Then' % (r, w))
                add('    Begin')
                add('        Cm.RemovePCBObject(A);')
                add('        Brd.RemovePCBObject(A);')
                add("        n := n + 1; Done := Done + ' %s';" % ref)
                add('    End;')
        if adding:
            add('    PCBServer.PostProcess;')
        add('    Brd.ViewManager_FullUpdate;')
        verb = 'Added' if adding else 'Removed'
        add("    ShowMessage('%s ' + IntToStr(n) + ' of %d pin-1 dots:' + Done + '. Run DRC, then File > Save.');" % (verb, len(marks)))
        add('End;')
        add('')
    open(OUT, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(lines) + '\n')
    prj = os.path.join(HERE, 'FabBPin1Dots.PrjScr')
    open(prj, 'w', encoding='utf-8', newline='\r\n').write('[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=FabBPin1Dots.pas\n')
    print('wrote %s (%d dots) and %s' % (OUT, len(marks), prj))


if __name__ == '__main__':
    main()

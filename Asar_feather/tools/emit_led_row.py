"""LED row and pin labels, 2026-11-06. Writes two DelphiScripts from tools/route/stage7/final/{model,labels}.led.json:

    tools/FeatherLedParts.pas    LedParts: LD5, LD1, LD2, LD0 into the row, R78, R83, R84 north of it
    tools/FeatherPinLabels.pas   PinLabels: RESET's designator off, the old BTN and ASAR A7 texts out, the new texts in, boxes logged to docs/labels.log

Run LedParts, then PinLabels, then the copper script (tools/FeatherCopper_S7L.pas from emit_copper.py) with asar_feather.PcbDoc focused.
Each part gets its rotation, then is shifted so the named pad lands exactly on the model's point."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
F = os.path.join(HERE, 'route', 'stage7', 'final')
M = json.load(open(os.path.join(F, 'model.led.json')))
L = json.load(open(os.path.join(F, 'labels.led.json')))
pad = {(p['ref'], p['pad']): p for p in M['pads']}
DOC = r"\Asar_feather\Asar_feather.PrjPcb\asar_feather.PcbDoc"
LOG = r"C:\Users\tambe\Documents\Electronics\Zulu_A7\Asar_feather\docs\labels.log"
PLACE = [('LD5', 0, 'A'), ('LD1', 180, 'A'), ('LD2', 180, 'A'), ('LD0', 0, '1'), ('R78', 180, '1'), ('R83', 180, '1'), ('R84', 180, '1')]
FOCUS = ["    Doc := GetWorkspace.DM_FocusedDocument;",
         "    If (Doc = Nil) Or (Pos('%s', Doc.DM_FullPath) = 0) Then" % DOC,
         "    Begin",
         "        ShowMessage('Refusing: focus Asar_feather\\Asar_feather.PrjPcb\\asar_feather.PcbDoc first.');",
         "        Exit;",
         "    End;",
         "    Brd := PCBServer.GetCurrentPCBBoard;"]


def prjscr(name):
    with open(os.path.join(HERE, name + '.PrjScr'), 'w', newline='\r\n') as f:
        f.write('[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=%s.pas\n' % name)


def parts():
    calls = ["    Place('%s', %d, '%s', %.4f, %.4f);" % (r, rot, pn, pad[(r, pn)]['x'], pad[(r, pn)]['y']) for r, rot, pn in PLACE]
    s = """{ FeatherLedParts.pas -- GENERATED by tools/emit_led_row.py, 2026-11-06. The four LEDs into an even row 3.2 mm apart at y 4.675, and R78, R83, R84
  north of it at y 6.3, so that the strip between X2's pads and the row stays free for pin labels. LD1, LD2 and the three resistors turn 180 degrees.
  Coordinates are board-relative and equal tools/route/stage7/final/model.led.json. Refuses unless LD1's pad A is still where the routed board had it,
  so it runs once. Run LedParts with asar_feather.PcbDoc focused, then PinLabels, then PlaceS7L. }

Var
    Brd : IPCB_Board;
    NDone : Integer;
    Missing : String;

Procedure Place(D : String; Rot : Double; PN : String; PX, PY : Double);
Var
    C  : IPCB_Component;
    It : IPCB_GroupIterator;
    P  : IPCB_Pad;
    FX, FY : TCoord;
    Got : Boolean;
Begin
    C := Brd.GetPcbComponentByRefDes(D);
    If C = Nil Then
    Begin
        Missing := Missing + D + ' ';
        Exit;
    End;
    C.BeginModify;
    C.Rotation := Rot;
    C.EndModify;
    Got := False;
    It := C.GroupIterator_Create;
    It.AddFilter_ObjectSet(MkSet(ePadObject));
    P := It.FirstPCBObject;
    While (P <> Nil) And (Not Got) Do
    Begin
        If P.Name = PN Then
        Begin
            FX := P.X;
            FY := P.Y;
            Got := True;
        End;
        P := It.NextPCBObject;
    End;
    C.GroupIterator_Destroy(It);
    If Not Got Then
    Begin
        Missing := Missing + D + '.' + PN + ' ';
        Exit;
    End;
    C.BeginModify;
    C.X := C.X + (Brd.XOrigin + MMsToCoord(PX) - FX);
    C.Y := C.Y + (Brd.YOrigin + MMsToCoord(PY) - FY);
    C.EndModify;
    NDone := NDone + 1;
End;

Procedure LedParts;
Var
    Doc : IDocument;
    C   : IPCB_Component;
    It  : IPCB_GroupIterator;
    P   : IPCB_Pad;
    Old : Boolean;
Begin
%s
    Old := False;
    C := Brd.GetPcbComponentByRefDes('LD1');
    It := C.GroupIterator_Create;
    It.AddFilter_ObjectSet(MkSet(ePadObject));
    P := It.FirstPCBObject;
    While P <> Nil Do
    Begin
        If (P.Name = 'A') And (Abs(CoordToMMs(P.X - Brd.XOrigin) - 40.03) < 0.01) And (Abs(CoordToMMs(P.Y - Brd.YOrigin) - 9.03) < 0.01) Then
            Old := True;
        P := It.NextPCBObject;
    End;
    C.GroupIterator_Destroy(It);
    If Not Old Then
    Begin
        ShowMessage('Refusing: LD1 pad A is not at 40.03, 9.03; the parts look moved already.');
        Exit;
    End;
    NDone := 0;
    Missing := '';
    PCBServer.PreProcess;
%s
    PCBServer.PostProcess;
    Brd.ViewManager_FullUpdate;
    ShowMessage('Placed ' + IntToStr(NDone) + ' of %d parts. Missing:' + Missing);
End;
""" % ('\n'.join(FOCUS), '\n'.join(calls), len(PLACE))
    with open(os.path.join(HERE, 'FeatherLedParts.pas'), 'w', newline='\r\n') as f:
        f.write(s)
    prjscr('FeatherLedParts')


def labels():
    calls = ["    AddLabel('%s', %.4f, %.4f, %d, %.3f, %.3f);" % (l['text'], l['anchor'][0], l['anchor'][1], l['rot'], l['size'], l['stroke']) for l in L]
    s = """{ FeatherPinLabels.pas -- GENERATED by tools/emit_led_row.py, 2026-11-06. Silk at PCBWay's minimum: 22 header pins get their Feather name, BTN goes above its
  switch at 0.8 mm, the title goes on two lines beside X5. RESET's designator goes off and the old free BTN and ASAR A7 texts go out first. Anchors are the lower
  left of the text as Altium places it, in board-relative mm; a rotated text turns about its anchor. Refuses if the SCK label exists, or if the two old texts are not
  both found, so it runs once. The boxes Altium computes are written to docs/labels.log. Run PinLabels with asar_feather.PcbDoc focused. }

Var
    Brd : IPCB_Board;
    Log : TStringList;

Procedure AddLabel(S : String; X, Y : Double; R : Integer; H, W : Double);
Var
    T : IPCB_Text;
    B : TCoordRect;
Begin
    T := PCBServer.PCBObjectFactory(eTextObject, eNoDimension, eCreate_Default);
    T.XLocation := Brd.XOrigin + MMsToCoord(X);
    T.YLocation := Brd.YOrigin + MMsToCoord(Y);
    T.Layer := eTopOverlay;
    T.Text := S;
    T.Size := MMsToCoord(H);
    T.Width := MMsToCoord(W);
    T.Rotation := R;
    T.UseTTFonts := False;
    Brd.AddPCBObject(T);
    PCBServer.SendMessageToRobots(Brd.I_ObjectAddress, c_Broadcast, PCBM_BoardRegisteration, T.I_ObjectAddress);
    B := T.BoundingRectangle;
    Log.Add(S + ' ' + FloatToStr(CoordToMMs(B.Left - Brd.XOrigin)) + ' ' + FloatToStr(CoordToMMs(B.Right - Brd.XOrigin)) + ' ' +
            FloatToStr(CoordToMMs(B.Bottom - Brd.YOrigin)) + ' ' + FloatToStr(CoordToMMs(B.Top - Brd.YOrigin)));
End;

Procedure PinLabels;
Var
    Doc  : IDocument;
    It   : IPCB_BoardIterator;
    T    : IPCB_Text;
    C    : IPCB_Component;
    Kill : TInterfaceList;
    i    : Integer;
    Dup  : Boolean;
Begin
%s
    Dup := False;
    Kill := TInterfaceList.Create;
    It := Brd.BoardIterator_Create;
    It.AddFilter_ObjectSet(MkSet(eTextObject));
    It.AddFilter_LayerSet(MkSet(eTopOverlay));
    It.AddFilter_Method(eProcessAll);
    T := It.FirstPCBObject;
    While T <> Nil Do
    Begin
        If Not T.InComponent Then
        Begin
            If T.Text = 'SCK' Then Dup := True;
            If (T.Text = 'BTN') Or (T.Text = 'ASAR A7') Then Kill.Add(T);
        End;
        T := It.NextPCBObject;
    End;
    Brd.BoardIterator_Destroy(It);
    If Dup Or (Kill.Count <> 2) Then
    Begin
        ShowMessage('Refusing: SCK label present or old texts not both found (' + IntToStr(Kill.Count) + '); nothing changed.');
        Kill.Free;
        Exit;
    End;
    Log := TStringList.Create;
    For i := 0 To Kill.Count - 1 Do Brd.RemovePCBObject(Kill.Items[i]);
    Kill.Free;
    C := Brd.GetPcbComponentByRefDes('RESET');
    C.BeginModify;
    C.NameOn := False;
    C.EndModify;
%s
    Log.SaveToFile('%s');
    Brd.ViewManager_FullUpdate;
    ShowMessage('Added ' + IntToStr(Log.Count) + ' of %d texts; boxes in docs\\labels.log.');
    Log.Free;
End;
""" % ('\n'.join(FOCUS), '\n'.join(calls), LOG, len(L))
    with open(os.path.join(HERE, 'FeatherPinLabels.pas'), 'w', newline='\r\n') as f:
        f.write(s)
    prjscr('FeatherPinLabels')


parts()
labels()
print('FeatherLedParts.pas:', len(PLACE), 'parts; FeatherPinLabels.pas:', len(L), 'texts')

"""Write the Feather pin constraints, vivado/asar_feather_pins.xdc (2026-10-23).

Starts from the production vivado/zulu_a7_pins.xdc and, checked against the Feather schematic netlist:
  - drops the ports of balls the Feather no longer connects (JA*, CHAN9-13, CHAN23-28);
  - renames the 19 header signals to their Feather pin names with an F_ prefix (F_A2 ... F_SDA, F_D4), because
    A0-A12 are already the SDRAM address ports;
  - keeps every other port name, IOSTANDARD, clock period and drive strength unchanged.
Every ball comes from the schematic netlist, so it carries all four re-pins (tools/pin_swap.json, then
tools/route/stage5/swapA_perm.json, swapB_perm.json and tools/route/stage7/final/x_perm_b_perm.json).
Every PACKAGE_PIN is cross-checked: the ball must carry that port's net in the schematic (sch_netlist.py).
    python tools/make_xdc.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import feather_map as M  # noqa: E402
from sch_netlist import build  # noqa: E402

SRC = os.path.join(ROOT, '..', 'vivado', 'zulu_a7_pins.xdc')
PKG = os.path.join(ROOT, '..', 'Datasheet', 'xc7a35tcpg236pkg_pinout.txt')
OUT = os.path.join(ROOT, 'vivado', 'asar_feather_pins.xdc')
LINE = re.compile(r'set_property -dict \{PACKAGE_PIN (\S+)\s+IOSTANDARD (\S+)\} \[get_ports \{(\S+)\}\]')


def main():
    nets = build(os.path.join(ROOT, 'Asar_feather.PrjPcb'))
    ball_net = {d: n for n, pins in nets.items() for r, d in pins if r == 'U1'}
    pkg = {}
    for line in open(PKG):
        f = line.split()
        if len(f) >= 4 and re.match(r'^[A-W]\d+$', f[0]):
            pkg[f[0]] = (f[1], f[3])
    feather_port = {}                                   # net -> F_ name
    for pad, (name, old, label) in M.FEATHER.items():
        net = next((n for n, pins in nets.items() if ('X2', str(pad)) in pins), None)
        if net and net.startswith('CHAN'):
            feather_port[net] = 'F_' + name
    out, dropped, checked = [], [], 0
    for line in open(SRC):
        m = LINE.match(line)
        if not m:
            out.append(line.rstrip('\n'))
            continue
        ball, std, port = m.groups()
        net = port.replace('_N', '#').replace('CHAN_CLK', 'CHAN-CLK').replace('_', '-')
        cands = [n for n in (port, net, port.replace('_N', '#'), port.replace('_', '-')) if n]
        net = next((n for n in cands if n in nets), None)
        if net is None or not any(r == 'U1' for r, d in nets[net]):
            dropped.append(port)
            continue
        new_ball = next(d for r, d in nets[net] if r == 'U1')
        new_port = feather_port.get(net, port)
        bank, pin_name = pkg[new_ball][1], pkg[new_ball][0]
        if ball_net.get(new_ball) != net:
            sys.exit('REFUSED: %s on %s is not net %s' % (new_port, new_ball, net))
        checked += 1
        comment = '%s  bank %s  %s' % (net, bank, pin_name)
        out.append('set_property -dict {PACKAGE_PIN %-4s IOSTANDARD %s} [get_ports {%s}]  ;# %s' % (
            new_ball, std, new_port, comment))
    text = '\n'.join(out) + '\n'
    text = text.replace('create_clock -period 20.000 -name chanclk [get_ports CHAN_CLK]',
                        'create_clock -period 20.000 -name chanclk [get_ports F_D4]')
    text = text.replace('# generated from zulu_a7.sch -- ball assignments exactly as drawn',
                        '# Asar A7 Feather -- generated by Asar_feather/tools/make_xdc.py from the production\n'
                        '# vivado/zulu_a7_pins.xdc; every ball checked against the Feather schematic netlist.\n'
                        '# Header signals are F_<Feather pin name>; A0/A1 are analog (XADC AD4 on G3/G2 and AD12 on\n'
                        '# H2/J2, through the R10-R17 dividers), not FPGA ports. Their nets are named AIN15_P/N and\n'
                        '# AIN16_P/N: inherited names that do not match the channels (AD15 is on SDRAM balls N2/N1,\n'
                        '# and the package pinout has no AD16). Balls: tools/pin_swap.json, then\n'
                        '# tools/route/stage5/swapA_perm.json and swapB_perm.json, then\n'
                        '# tools/route/stage7/final/x_perm_b_perm.json.')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', newline='\n').write(text)
    print('%s: %d pins checked against the netlist; dropped %d ports: %s' % (
        os.path.relpath(OUT, ROOT), checked, len(dropped), ' '.join(sorted(dropped))))
    for net, port in sorted(feather_port.items(), key=lambda t: t[1]):
        print('  %-7s %-8s %s' % (port, net, next(d for r, d in nets[net] if r == 'U1')))


if __name__ == '__main__':
    main()

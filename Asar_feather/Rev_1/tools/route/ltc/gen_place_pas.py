"""Write a DelphiScript that places the LTC3556 block from a placement JSON (2026-11-10).

    python gen_place_pas.py <model.json> <placement.json> <Name> <board guard substring> <out dir>

Each part goes to the Bottom side at its rotation, then is moved so its pad 1 lands on the planned point
(pad-anchored, as AsarTpsPlace); every pad is then checked within 0.005 mm. Designators and comments are hidden
(Bottom parts hide theirs on these boards) and the switch nodes join the PWR_SWITCH class.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import place_check as PC  # noqa: E402

M = json.load(open(sys.argv[1]))
P = json.load(open(sys.argv[2]))
name, guard, outdir = sys.argv[3], sys.argv[4].replace('/', chr(92)), sys.argv[5]
nets = {(p['ref'], p['pad']): p['net'] for p in M['pads']}
sw = sorted({p['net'] for p in M['pads'] if p['net'].startswith('PWR_SW')})
tpl = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'AsarTpsPlace2.pas')).read()
head = tpl[tpl.index('Var\n'):tpl.index('Procedure AsarTpsPlace2;')]
L = ['{ %s.pas -- GENERATED by tools/route/ltc/gen_place_pas.py from %s; do not edit by hand.' % (name, os.path.basename(sys.argv[2])),
     '  Place%s: the LTC3556 power block (%d parts) to the Bottom side, pad-anchored, every pad checked; hides the' % (name, len(P)),
     '  designators and adds %s to PWR_SWITCH. Then run the copper script, Rebuild%s, save. }' % (' '.join(sw), name), '']
L.append(head.replace('Procedure Place(', 'Procedure Place(').rstrip() + '\n')
L += ['Procedure Place%s;' % name, 'Var', '    Doc : IDocument;', '    It : IPCB_BoardIterator;', '    Cls : IPCB_ObjectClass;',
      '    Cm : IPCB_Component;', 'Begin', '    Doc := GetWorkspace.DM_FocusedDocument;',
      "    If (Doc = Nil) Or (Pos('%s', Doc.DM_FullPath) = 0) Then" % guard,
      "    Begin ShowMessage('Refusing: focus %s first.'); Exit; End;" % guard,
      '    Brd := PCBServer.GetCurrentPCBBoard;', "    Missing := ''; Report := ''; NDone := 0; NBad := 0;", '    PCBServer.PreProcess;']
checks = []
for ref, (side, x, y, rot) in P.items():
    ps = PC.pads_of(ref, side, x, y, rot, nets)
    p1 = [p for p in ps if p['pad'] == '1'][0]
    L.append("    Place('%s', %d, '1', %.4f, %.4f);" % (ref, round(rot) % 360, p1['x'], p1['y']))
    L.append("    Cm := Brd.GetPcbComponentByRefDes('%s'); If Cm <> Nil Then Begin Cm.BeginModify; Cm.NameOn := False; Cm.CommentOn := False; Cm.EndModify; End;" % ref)
    for p in ps:
        checks.append("    Check('%s', '%s', %.4f, %.4f);" % (ref, p['pad'], p['x'], p['y']))
L += ['    It := Brd.BoardIterator_Create;', '    It.AddFilter_ObjectSet(MkSet(eClassObject));', '    It.AddFilter_LayerSet(AllLayers);',
      '    It.AddFilter_Method(eProcessAll);', '    Cls := It.FirstPCBObject;', '    While Cls <> Nil Do', '    Begin',
      "        If (Cls.MemberKind = eClassMemberKind_Net) And (Cls.Name = 'PWR_SWITCH') Then",
      '        Begin']
for n in sw:
    L.append("            If Not Cls.IsMember('%s') Then Cls.AddMemberByName('%s');" % (n, n))
L += ['        End;', '        Cls := It.NextPCBObject;', '    End;', '    Brd.BoardIterator_Destroy(It);', '    PCBServer.PostProcess;']
L += checks
L += ['    Brd.ViewManager_FullUpdate;',
      "    ShowMessage('Placed ' + IntToStr(NDone) + ' of %d. Missing: ' + Missing + ' Pads off plan: ' + IntToStr(NBad) + ' ' + Report + 'Undo if anything is off; else run the copper script.');" % len(P),
      'End;', '']
rb = tpl[tpl.index('Procedure AsarTpsRebuild2;'):]
L.append(rb.replace('AsarTpsRebuild2', 'Rebuild%s' % name))
open(os.path.join(outdir, name + '.pas'), 'w', newline='\n').write('\n'.join(L))
open(os.path.join(outdir, name + '.PrjScr'), 'w', newline='\n').write('[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=%s.pas\n' % name)
print('wrote', name, len(P), 'parts,', len(checks), 'pad checks, classes', sw)

"""Emit the Altium DelphiScript for the 2026-11-24 X2 label swap + title/U1/U4 silk move, from a final_<tag>.json plan.
Only API names already proven in this project: BoardIterator text scan, T.Text/XLocation/YLocation in BeginModify/
EndModify, Brd.RemovePCBObject, GetPcbComponentByRefDes + NameOn. Printed U1/U4 labels are free texts reused from
deleted pin numbers ('23', '24'; Rev 3's horizontal GND reuses '22'), because a designator XLocation write does not
stick in this Altium (memory: altium-delphiscript-traps).
usage: python emit_silk_pas.py <geom.json> <final.json> <tag> <path fragment> <proc name> <out.pas> <ops.json>"""
import json
import sys

geom, final, tag, frag, proc, out_pas, out_ops = sys.argv[1:8]
G = json.load(open(geom))
E = json.load(open(final))
T = {t['idx']: t for t in G['texts']}


def free(idx):
    t = T[int(idx)]
    assert t['kind'] == 'free' and t['layer'] == 33, t
    return t


def num(s):
    h = [t for t in G['texts'] if t['layer'] == 33 and t['kind'] == 'free' and t['text'] == s and abs(t['y'] - 2.411) < 1e-3]
    assert len(h) == 1, s
    return h[0]


mods, dels, hide = [], [], []
reuse = {}
for k, v in E['set'].items():
    t = T[int(k)]
    if t['kind'] == 'designator':
        donor = num({'U1': '23', 'U4': '24'}[t['ref']])
        reuse[donor['idx']] = (t['ref'], v['x'], v['y'])
        if t['ref'] == 'U1':
            hide.append('U1')
        continue
    if 'rot' in v and round(v['rot']) != round(t['rot']):          # Rev 3 pin 21: vertical '21' -> horizontal 'GND'
        donor = num('22')
        reuse[donor['idx']] = (v['text'], v['x'], v['y'])
        dels.append(t)
        continue
    mods.append((t, v.get('text', t['text']), v.get('x', t['x']) - t['x'], v.get('y', t['y']) - t['y']))
for i in E['delete']:
    if int(i) in reuse:
        continue
    dels.append(free(i))
for i, (s, x, y) in reuse.items():
    t = free(i)
    mods.append((t, s, x - t['x'], y - t['y']))

# ops in check_silk format (what the script really does), for the expected-state check
ops = {'delete': [t['idx'] for t in dels], 'set': {}}
for t, s, dx, dy in mods:
    ops['set'][str(t['idx'])] = {'text': s, 'x': round(t['x'] + dx, 4), 'y': round(t['y'] + dy, 4)}
for r in hide:
    d = [t for t in G['texts'] if t['kind'] == 'designator' and t['ref'] == r][0]
    ops['set'][str(d['idx'])] = {'shown': False}
json.dump(ops, open(out_ops, 'w'), indent=1)

# every free Top Overlay text must be unique by (text, x, y), or the finder would refuse
seen = set()
for t in G['texts']:
    if t['layer'] == 33 and t['kind'] == 'free':
        k = (t['text'], round(t['x'], 3), round(t['y'], 3))
        assert k not in seen, k
        seen.add(k)

L = []
a = L.append
a("{ %s.pas -- 2026-11-24, %s: X2 pin labels -- each name takes its pin number's place and the numbers go;" % (proc, tag))
a('  the board title moves down 1.23 mm; the printed U1 label moves under the FPGA and a U4 label is printed right of U4.')
a('  Generated by emit_silk_pas.py from final_%s.json: %d texts changed, %d deleted%s.' % (
    tag, len(mods), len(dels), ', U1 designator hidden' if hide else ''))
a('  The U1 / U4 labels are free texts (reused pin numbers 23 / 24): a designator XLocation write does not stick here.')
a('  Every text is found by its exact text and position (board mm from the origin) BEFORE anything changes;')
a('  it refuses unless each is found exactly once. Save, DRC, then save again after the clean DRC. }')
a('Function FindFree(B : IPCB_Board; S : String; X, Y : Double) : IPCB_Text;')
a('Var')
a('    It : IPCB_BoardIterator;')
a('    T  : IPCB_Text;')
a('    n  : Integer;')
a('Begin')
a('    Result := Nil;')
a('    n := 0;')
a('    It := B.BoardIterator_Create;')
a('    It.AddFilter_ObjectSet(MkSet(eTextObject));')
a('    It.AddFilter_LayerSet(MkSet(eTopOverlay));')
a('    It.AddFilter_Method(eProcessAll);')
a('    T := It.FirstPCBObject;')
a('    While T <> Nil Do')
a('    Begin')
a('        If (Not T.InComponent) And (T.Text = S) Then')
a('            If (Abs(CoordToMMs(T.XLocation - B.XOrigin) - X) < 0.002) And (Abs(CoordToMMs(T.YLocation - B.YOrigin) - Y) < 0.002) Then')
a('            Begin')
a('                Result := T;')
a('                n := n + 1;')
a('            End;')
a('        T := It.NextPCBObject;')
a('    End;')
a('    B.BoardIterator_Destroy(It);')
a('    If n <> 1 Then Result := Nil;')
a('End;')
a('')
a('Procedure %s;' % proc)
a('Var')
a('    Doc : IDocument;')
a('    B   : IPCB_Board;')
a('    T   : IPCB_Text;')
a('    Cm  : IPCB_Component;')
a('    ML, DL : TInterfaceList;')
a('    Missing : String;')
a('    i : Integer;')
a('Begin')
a('    Doc := GetWorkspace.DM_FocusedDocument;')
a("    If (Doc = Nil) Or (Pos('%s', Doc.DM_FullPath) = 0) Then" % frag)
a('    Begin')
a("        ShowMessage('Refusing: focus %s first.');" % frag.replace('\\', '/'))
a('        Exit;')
a('    End;')
a('    B := PCBServer.GetCurrentPCBBoard;')
a('    ML := TInterfaceList.Create;')
a('    DL := TInterfaceList.Create;')
a("    Missing := '';")
for t, s, dx, dy in mods:
    a("    T := FindFree(B, '%s', %.4f, %.4f);" % (t['text'], t['x'], t['y']))
    a("    If T = Nil Then Missing := Missing + ' [%s @ %.3f,%.3f]' Else ML.Add(T);" % (t['text'], t['x'], t['y']))
for t in dels:
    a("    T := FindFree(B, '%s', %.4f, %.4f);" % (t['text'], t['x'], t['y']))
    a("    If T = Nil Then Missing := Missing + ' [%s @ %.3f,%.3f]' Else DL.Add(T);" % (t['text'], t['x'], t['y']))
for r in hide:
    a("    If B.GetPcbComponentByRefDes('%s') = Nil Then Missing := Missing + ' [component %s]';" % (r, r))
a("    If Missing <> '' Then")
a('    Begin')
a("        ShowMessage('Refusing, nothing changed. Not found exactly once:' + Missing);")
a('        Exit;')
a('    End;')
a('    If (ML.Count <> %d) Or (DL.Count <> %d) Then' % (len(mods), len(dels)))
a('    Begin')
a("        ShowMessage('Refusing, nothing changed: list counts differ.');")
a('        Exit;')
a('    End;')
a('    PCBServer.PreProcess;')
for k, (t, s, dx, dy) in enumerate(mods):
    a('    T := ML.Items[%d];' % k)
    a('    T.BeginModify;')
    if s != t['text']:
        a("    T.Text := '%s';" % s)
    if abs(dx) > 1e-6:
        a('    T.XLocation := T.XLocation + MMsToCoord(%.4f);' % dx)
    if abs(dy) > 1e-6:
        a('    T.YLocation := T.YLocation + MMsToCoord(%.4f);' % dy)
    a('    T.EndModify;')
a('    For i := 0 To DL.Count - 1 Do B.RemovePCBObject(DL.Items[i]);')
for r in hide:
    a("    Cm := B.GetPcbComponentByRefDes('%s');" % r)
    a('    Cm.BeginModify;')
    a('    Cm.NameOn := False;')
    a('    Cm.EndModify;')
a('    PCBServer.PostProcess;')
a('    B.ViewManager_FullUpdate;')
a("    ShowMessage('%s done: %d texts changed, %d deleted%s. Save, then DRC.');" % (
    proc, len(mods), len(dels), ', U1 designator hidden' if hide else ''))
a('End;')
with open(out_pas, 'w', newline='\r\n') as f:
    f.write('\n'.join(L) + '\n')
with open(out_pas[:-4] + '.PrjScr', 'w', newline='\r\n') as f:
    f.write('[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=%s\n' % out_pas.replace('\\', '/').split('/')[-1])
print(out_pas, 'mods', len(mods), 'dels', len(dels), 'hide', hide)

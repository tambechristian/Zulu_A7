"""Emit the DelphiScript that moves R4's printed label off the X2 pin-name row (2026-11-24, owner: "Yes, move R4").
R4's designator is hidden and a free Top Overlay text 'R4' is placed under the R4 array (a designator XLocation write
does not hold in this Altium). Text creation as tools/FeatherBtnLabel.pas (Asar), proven on a board document.
usage: python emit_r4_pas.py <path fragment> <proc> <out.pas>"""
import sys

frag, proc, out = sys.argv[1:4]
X, Y, H, W = 58.633, 13.85, 0.8, 0.15
L = r"""{ %(proc)s.pas -- 2026-11-24: R4's label leaves the X2 pin-name row (it read as pin 1's name). R4's designator is
  hidden and a free Top Overlay text 'R4' (0.8 mm, 0.15 mm stroke, the X2 names' size) goes under the R4 array at
  (%(X).3f, %(Y).3f), centred on the array. Generated by emit_r4_pas.py. Refuses unless R4's designator still prints at
  (58.623, 22.098) and no free 'R4' text exists yet. Save, DRC, then export. }
Procedure %(proc)s;
Var
    Doc : IDocument;
    Brd : IPCB_Board;
    Cm  : IPCB_Component;
    It  : IPCB_BoardIterator;
    T   : IPCB_Text;
    R   : TCoordRect;
    n   : Integer;
Begin
    Doc := GetWorkspace.DM_FocusedDocument;
    If (Doc = Nil) Or (Pos('%(frag)s', Doc.DM_FullPath) = 0) Then
    Begin
        ShowMessage('Refusing: focus %(fragslash)s first.');
        Exit;
    End;
    Brd := PCBServer.GetCurrentPCBBoard;
    Cm := Brd.GetPcbComponentByRefDes('R4');
    If Cm = Nil Then
    Begin
        ShowMessage('Refusing: component R4 not found.');
        Exit;
    End;
    If (Not Cm.NameOn) Or (Abs(CoordToMMs(Cm.Name.XLocation - Brd.XOrigin) - 58.623) > 0.002) Or
       (Abs(CoordToMMs(Cm.Name.YLocation - Brd.YOrigin) - 22.098) > 0.002) Then
    Begin
        ShowMessage('Refusing: R4''s designator is not printing at (58.623, 22.098); nothing changed.');
        Exit;
    End;
    n := 0;
    It := Brd.BoardIterator_Create;
    It.AddFilter_ObjectSet(MkSet(eTextObject));
    It.AddFilter_LayerSet(MkSet(eTopOverlay));
    It.AddFilter_Method(eProcessAll);
    T := It.FirstPCBObject;
    While T <> Nil Do
    Begin
        If (Not T.InComponent) And (T.Text = 'R4') Then n := n + 1;
        T := It.NextPCBObject;
    End;
    Brd.BoardIterator_Destroy(It);
    If n <> 0 Then
    Begin
        ShowMessage('Refusing: a free R4 text already exists; nothing changed.');
        Exit;
    End;
    Cm.BeginModify;
    Cm.NameOn := False;
    Cm.EndModify;
    T := PCBServer.PCBObjectFactory(eTextObject, eNoDimension, eCreate_Default);
    T.XLocation := Brd.XOrigin + MMsToCoord(%(X).4f);
    T.YLocation := Brd.YOrigin + MMsToCoord(%(Y).4f);
    T.Layer := eTopOverlay;
    T.Text := 'R4';
    T.Size := MMsToCoord(%(H).4f);
    T.Width := MMsToCoord(%(W).4f);
    T.Rotation := 0;
    T.UseTTFonts := False;
    Brd.AddPCBObject(T);
    PCBServer.SendMessageToRobots(Brd.I_ObjectAddress, c_Broadcast, PCBM_BoardRegisteration, T.I_ObjectAddress);
    R := T.BoundingRectangle;
    Brd.ViewManager_FullUpdate;
    ShowMessage('%(proc)s done: R4 designator hidden, R4 label box x ' + FloatToStr(CoordToMMs(R.Left - Brd.XOrigin)) + '..' +
                FloatToStr(CoordToMMs(R.Right - Brd.XOrigin)) + ' y ' + FloatToStr(CoordToMMs(R.Bottom - Brd.YOrigin)) + '..' +
                FloatToStr(CoordToMMs(R.Top - Brd.YOrigin)) + '. Save, then DRC.');
End;
""" % dict(proc=proc, frag=frag, fragslash=frag.replace('\\', '/'), X=X, Y=Y, H=H, W=W)
with open(out, 'w', newline='\r\n') as f:
    f.write(L)
with open(out[:-4] + '.PrjScr', 'w', newline='\r\n') as f:
    f.write('[Design]\nVersion=1.0\n\n[Document1]\nDocumentPath=%s\n' % out.replace('\\', '/').split('/')[-1])
print(out)
